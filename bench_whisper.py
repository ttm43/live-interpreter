"""faster-whisper vs offline Parakeet, same conditions: full-file offline
decode on the same test set. Measures transcript quality + CPU speed.

Note: testclips/refs.json pseudo-references were GENERATED by Parakeet, so
WER on those clips is biased in Parakeet's favour — judge those by reading
the transcripts; the LibriSpeech rows (0/1.wav) have human ground truth.
"""
import sys
import time
import wave
from pathlib import Path

import numpy as np

sys.stdout.reconfigure(encoding="utf-8", errors="replace")

from bench_asr import REFERENCES, wer
from interpreter.config import ASR_EN_MODEL_DIR, MODELS_DIR

CLIPS_DIR = Path(__file__).resolve().parent / "testclips"
WAVS = [ASR_EN_MODEL_DIR / "test_wavs" / n for n in ("0.wav", "1.wav")]
WAVS += sorted(CLIPS_DIR.glob("*.wav"))


def read_wav(path: Path) -> tuple[np.ndarray, int]:
    with wave.open(str(path)) as f:
        data = np.frombuffer(f.readframes(f.getnframes()), dtype=np.int16)
        return data.astype(np.float32) / 32768.0, f.getframerate()


def report(name: str, path: Path, text: str, elapsed: float, dur: float) -> None:
    line = f"  {path.name}: RTF {elapsed / dur:.2f}"
    if path.name in REFERENCES:
        line += f" | WER {wer(text, REFERENCES[path.name]) * 100:.1f}%"
    print(line)
    print(f"    -> {text[:170]}")


def bench_whisper(model_name: str) -> None:
    from faster_whisper import WhisperModel

    t0 = time.monotonic()
    model = WhisperModel(model_name, device="cpu", compute_type="int8", cpu_threads=8)
    print(f"== faster-whisper {model_name} (loaded in {time.monotonic() - t0:.1f}s)")
    for path in WAVS:
        samples, sr = read_wav(path)
        t0 = time.monotonic()
        segments, _ = model.transcribe(str(path), language="en", beam_size=5)
        text = " ".join(s.text.strip() for s in segments)
        report(model_name, path, text, time.monotonic() - t0, len(samples) / sr)


def bench_parakeet_offline() -> None:
    import sherpa_onnx

    d = MODELS_DIR / "sherpa-onnx-nemo-parakeet-tdt-0.6b-v3-int8"
    t0 = time.monotonic()
    rec = sherpa_onnx.OfflineRecognizer.from_transducer(
        encoder=str(d / "encoder.int8.onnx"), decoder=str(d / "decoder.int8.onnx"),
        joiner=str(d / "joiner.int8.onnx"), tokens=str(d / "tokens.txt"),
        num_threads=8, model_type="nemo_transducer",
    )
    print(f"== parakeet-tdt-0.6b-v3 offline (loaded in {time.monotonic() - t0:.1f}s)")
    for path in WAVS:
        samples, sr = read_wav(path)
        t0 = time.monotonic()
        stream = rec.create_stream()
        stream.accept_waveform(sr, samples)
        rec.decode_stream(stream)
        report("parakeet", path, stream.result.text.strip(),
               time.monotonic() - t0, len(samples) / sr)


if __name__ == "__main__":
    bench_parakeet_offline()
    for m in sys.argv[1:] or ["large-v3-turbo", "large-v3"]:
        bench_whisper(m)
